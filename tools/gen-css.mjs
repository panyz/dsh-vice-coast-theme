// Emit mockups/tokens.css from palette.mjs (+ the real stock palette, when
// research/stock-tokens.json exists) so the mockup uses the same variable names
// the shipped shell uses. Nothing in the mockup hardcodes a theme colour.
import { writeFileSync } from 'node:fs';
import { existsSync, readFileSync } from 'node:fs';
import { palettes } from '../palette.mjs';

const out = ['/* generated by tools/gen-css.mjs — do not edit */'];

const fmt = (obj) => Object.entries(obj).map(([k, v]) => `  ${k}: ${v};`).join('\n');
out.push(`:root[data-theme="dark"] {\n${fmt(palettes.dark)}\n}`);
out.push(`:root[data-theme="light"] {\n${fmt(palettes.light)}\n}`);

// stock fallback, for the before/after strip: real values lifted from the
// installed shell (research/stock-tokens.json), never invented.
if (existsSync('research/stock-tokens.json')) {
  try {
    const stock = JSON.parse(readFileSync('research/stock-tokens.json', 'utf8'));
    const blocks = stock.selectors ?? {};
    const pick = (re) => Object.entries(blocks).find(([sel]) => re.test(sel))?.[1];
    const lightBlock = pick(/^body$/) ?? pick(/light/i);
    const darkBlock = pick(/dark/i) ?? pick(/prefers-color-scheme:\s*dark/i);
    if (lightBlock) out.push(`:root[data-theme="stock"] {\n${fmt(lightBlock)}\n}`);
    if (darkBlock) out.push(`:root[data-theme="stock-dark"] {\n${fmt(darkBlock)}\n}`);
  } catch (e) {
    console.warn('stock tokens present but unreadable:', e.message);
  }
}

writeFileSync('mockups/tokens.css', out.join('\n\n') + '\n');
const n = (o) => Object.keys(o).length;
console.log(`mockups/tokens.css — dark ${n(palettes.dark)} tokens, light ${n(palettes.light)} tokens`);
